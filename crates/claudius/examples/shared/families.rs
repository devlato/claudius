/// the family of a song with these tags, or "other"
pub fn family(tags: &BTreeSet<&str>) -> &'static str {
    FAMILIES.iter().find(|(_, ts)| ts.iter().any(|t| tags.contains(t))).map_or("other", |(f, _)| f)
}
